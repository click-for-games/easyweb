#!/usr/bin/env python3
"""Generate src/packages.c from the packages/ folder.

The easyweb binaries ship with the official packages baked in, so
`webhelp install animateeasy` works even without a network connection.

Usage:  python tools/sync_packages.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PKG_DIR = os.path.join(ROOT, "packages")
OUT = os.path.join(ROOT, "src", "packages.c")


def c_string(text: str) -> str:
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 32:
            out.append("\\%03o" % ord(ch))
        else:
            out.append(ch)
    # split into chunks so no single literal gets crazy long
    text = "".join(out)
    chunks = []
    cur = ""
    for piece in text.split("\\n"):
        if len(cur) + len(piece) > 90:
            chunks.append(cur)
            cur = ""
        cur += piece + "\\n"
    if cur:
        chunks.append(cur)
    if not chunks:
        chunks = [""]
    return "\n".join('    "%s"' % c for c in chunks)


def main() -> int:
    if not os.path.isdir(PKG_DIR):
        print("no packages folder found", file=sys.stderr)
        return 1

    names = sorted(
        d for d in os.listdir(PKG_DIR) if os.path.isdir(os.path.join(PKG_DIR, d))
    )

    parts = [
        "/* easyweb - official packages, generated by tools/sync_packages.py. Do not edit by hand. */",
        '#include "ew.h"',
        "",
    ]

    entries = []
    for name in names:
        pdir = os.path.join(PKG_DIR, name)
        manifest_path = os.path.join(pdir, "manifest.json")
        if not os.path.exists(manifest_path):
            continue
        with open(manifest_path, "r", encoding="utf-8") as fh:
            manifest = json.load(fh)

        def read(rel):
            path = os.path.join(pdir, rel)
            if not os.path.exists(path):
                return ""
            with open(path, "r", encoding="utf-8") as fh:
                return fh.read()

        entry_file = manifest.get("entry", name + ".eweb")
        css_file = manifest.get("css", "") or ""
        js_file = manifest.get("js", "") or ""

        entry = read(entry_file)
        css = read(css_file) if css_file else ""
        js = read(js_file) if js_file else ""

        var = "pkg_" + name.replace("-", "_")
        parts.append("static const char %s_entry_file[] = \"%s\";" % (var, entry_file))
        parts.append("static const char %s_css_file[] = \"%s\";" % (var, css_file))
        parts.append("static const char %s_js_file[] = \"%s\";" % (var, js_file))
        parts.append("static const char %s_entry[] =" % var)
        parts.append(c_string(entry) + ";")
        parts.append("static const char %s_css[] =" % var)
        parts.append(c_string(css) + ";")
        parts.append("static const char %s_js[] =" % var)
        parts.append(c_string(js) + ";")
        parts.append("")

        desc = manifest.get("description", "").replace('"', '\\"')
        entries.append(
            '    {"%s", "%s", "%s", %s_entry_file, %s_css_file, %s_js_file, %s_entry, %s_css, %s_js},'
            % (
                manifest.get("name", name),
                manifest.get("version", "1.0.0"),
                desc,
                var,
                var,
                var,
                var,
                var,
                var,
            )
        )

    parts.append("static const EmbeddedPkg EMBEDDED[] = {")
    parts.extend(entries)
    parts.append("};")
    parts.append("")
    parts.append("const EmbeddedPkg* embedded_packages(int* count) {")
    parts.append("  if (count) *count = (int)(sizeof(EMBEDDED) / sizeof(EMBEDDED[0]));")
    parts.append("  return EMBEDDED;")
    parts.append("}")
    parts.append("")

    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(parts))

    print("wrote %s with %d package(s)" % (OUT, len(entries)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
